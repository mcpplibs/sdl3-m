#!/usr/bin/env python3
"""Write the module sources from SDL 3.4.18's headers (tools/inventory.py)
and the decisions of tools/policy.py:

- src/sdl3.cppm: every declaration of the wrapped headers by `export using`
  (the upstream globals, unchanged), each under the #if its header declares
  it under, and the adaptations of the `SDL_FORCE_INLINE` API;
- src/inline.cpp: those adaptations, each calling upstream's own;
- src/macros.cppm: the macros, in mcpplibs::mwrap::sdl3::macros, as
  constants (object-like) and functions (FUNCTION_MACROS), each captured from
  the macro itself while it is still defined;
- src/macros.cpp: the function macros that may call a static inline function.

With --check nothing is written, and a difference fails.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import ROOTS, fetch, surface, Surface  # noqa: E402
import policy  # noqa: E402

VERSION = '3.4.18'
NOTICE = f'// Generated by tools/gen_exports.py from SDL {VERSION}\'s headers — do not edit by hand.\n'

INCLUDES = '''#ifndef SDL_MAIN_HANDLED
#define SDL_MAIN_HANDLED 1  // SDL_main.h's functions, not its main() machinery
#endif
#include <SDL3/SDL.h>
#include <SDL3/SDL_main.h>
#include <SDL3/SDL_revision.h>
#include <SDL3/SDL_vulkan.h>
'''


# ── classification ──────────────────────────────────────────────────────────

def exported_entries(s: Surface):
    """(entry, condition) in header order, for `export using`."""
    out = []
    for h in s.order:
        for d, _, _ in s.headers[h].decls:
            e = s.entries[d.name]
            if e.header != h or d.name in policy.EXCLUDED_DECLS or e.kind == 'inline':
                continue
            if any(x[0] is e for x in out):
                continue
            out.append((e, s.condition(e.places)))
    return out


def macro_class(s: Surface, name: str) -> tuple[str, str]:
    """('constant'|'string'|'function'|'side'|'excluded'|'adapted', reason)."""
    ms = s.macros[name]
    first = ms[0]
    if name in policy.EXCLUDED_MACROS:
        return 'excluded', policy.EXCLUDED_MACROS[name]
    if name in policy.SIDE_HEADER:
        return 'side', policy.SIDE_HEADER[name]
    if first.header in policy.SIDE_HEADER_FILES:
        return 'side', policy.SIDE_HEADER_FILES[first.header]
    if all(policy.is_include_guard(m) for m in ms):
        return 'excluded', 'include guard'
    if name in policy.FUNCTION_MACROS:
        return 'function', ''
    if name in s.transient:
        return 'excluded', 'defined and #undef-ined again inside its header'
    if name in s.entries:
        return 'error', 'a macro over a declared name; list it in policy.py'
    if any(m.params is not None for m in ms):
        return 'error', 'a function-like macro; map it in FUNCTION_MACROS or list it in policy.py'
    if all(m.body == '' for m in ms):
        return 'error', 'an empty macro; list it in policy.py'
    return ('string' if is_string(s, name, set()) else 'constant'), ''


def is_string(s: Surface, name: str, seen: set) -> bool:
    if name in seen:
        return False
    seen.add(name)
    for m in s.macros.get(name, []):
        body = m.body.strip()
        while body.startswith('('):
            body = body[1:].lstrip()
        if re.match(r'(u8|u|U|L)?"', body):
            return True
        t = re.match(r'(\w+)', body)
        if t and (re.fullmatch(r'PRI\w+', t.group(1)) or is_string(s, t.group(1), seen)):
            return True
    return False


def macro_table(s: Surface):
    """Every macro name in definition order, with its header and class."""
    out = []
    for h in s.order:
        for m in s.headers[h].macros:
            if s.macros[m.name][0] is not m:
                continue
            kind, reason = macro_class(s, m.name)
            out.append((m.name, h, kind, reason))
    return out


def arg_names(params: str) -> list[str]:
    out = []
    for p in [p.strip() for p in params.split(',') if p.strip()]:
        m = re.search(r'\(\s*&\s*(\w+)\s*\)', p) or re.search(r'(\w+)\s*$', p)
        out.append(m.group(1))
    return out


# ── rendering ───────────────────────────────────────────────────────────────

def conditional(lines_by_cond):
    """[(condition|None, line)] -> text, consecutive equal conditions grouped."""
    out, current = [], None
    for cond, line in lines_by_cond:
        if cond != current:
            if current is not None:
                out.append('#endif')
            if cond is not None:
                out.append(f'#if {cond}')
            current = cond
        out.append(line)
    if current is not None:
        out.append('#endif')
    return out


def render_module(s: Surface, macro_names: set[str]) -> tuple[str, str]:
    entries = exported_entries(s)
    counts = {}
    for e, _ in entries:
        counts[e.kind] = counts.get(e.kind, 0) + 1
    out = [NOTICE, f'''//
// mcpplibs.mwrap.sdl3 — SDL 3, the cross-platform window, input, audio, GPU and
// platform layer, as a C++ module. Every exported name is the upstream global
// of <SDL3/SDL.h> (and SDL_vulkan.h, SDL_main.h's functions, SDL_revision.h),
// unchanged: {counts.get('function', 0)} functions, {counts.get('type', 0) + counts.get('tag', 0)} types and {counts.get('enumerator', 0)} enumerators,
// each under the #if its header declares it under. The root also re-exports
// the macro mappings (mcpplibs.mwrap.sdl3.macros). The library is
// compat.sdl3, built from the same release.
//
// The SDL_FORCE_INLINE API (internal linkage, not exportable) is adapted in
// namespace mcpplibs::mwrap::sdl3 under the same names and signatures, each
// calling upstream's own (src/inline.cpp).
module;
''' + INCLUDES + '''
export module mcpplibs.mwrap.sdl3;

export import mcpplibs.mwrap.sdl3.macros;
''']
    by_header: dict[str, list] = {}
    for e, cond in entries:
        by_header.setdefault(e.header, []).append((e, cond))
    for h in s.order:
        items = by_header.get(h)
        if not items:
            continue
        out.append(f'\n// <SDL3/{h}>')
        lines = []
        for e, cond in items:
            if e.name in macro_names:
                # A macro of the same name (SDL_memcpy -> memcpy ...): the
                # declaration is what the module exports.
                lines.append((cond, f'#undef {e.name}'))
            lines.append((cond, f'export using ::{e.name};'))
        out += conditional(lines)
    out.append(f'\n// The SDL_FORCE_INLINE API ({len(policy.ADAPTED)}), adapted (src/inline.cpp).')
    out.append('export namespace mcpplibs::mwrap::sdl3 {')
    for name, (ret, params) in policy.ADAPTED.items():
        out.append(f'#undef {name}')
        out.append(f'{ret} {name}({params});')
    out.append('}  // namespace mcpplibs::mwrap::sdl3\n')
    cppm = '\n'.join(out)

    impl = [NOTICE, '''//
// The adaptations of the SDL_FORCE_INLINE API: each calls upstream's own
// (a static inline function, or on some compilers a macro over a builtin).
module;
''' + INCLUDES + '''
module mcpplibs.mwrap.sdl3;

namespace {
''']
    for name, (ret, params) in policy.ADAPTED.items():
        args = ', '.join(arg_names(params))
        impl.append(f'{ret} call_{name}({params}) {{ return {name}({args}); }}')
    impl.append('}  // namespace\n')
    for name in policy.ADAPTED:
        impl.append(f'#undef {name}')
    impl.append('\nnamespace mcpplibs::mwrap::sdl3 {\n')
    for name, (ret, params) in policy.ADAPTED.items():
        args = ', '.join(arg_names(params))
        impl.append(f'{ret} {name}({params}) {{ return call_{name}({args}); }}')
    impl.append('\n}  // namespace mcpplibs::mwrap::sdl3\n')
    return cppm, '\n'.join(impl)


def render_macros(s: Surface, table) -> tuple[str, str]:
    consts = [(n, h, k) for n, h, k, _ in table if k in ('constant', 'string')]
    funcs = [(n, h) for n, h, k, _ in table if k == 'function']
    side = sum(1 for *_, k, _ in table if k == 'side')
    excluded = sum(1 for *_, k, _ in table if k == 'excluded')
    out = [NOTICE, f'''//
// mcpplibs.mwrap.sdl3.macros — the macros of SDL 3's headers (a named module
// cannot export a macro), under their original names in
// mcpplibs::mwrap::sdl3::macros:
//
//   - {len(consts)} object-like macros as `inline constexpr` constants of the
//     macro's own type (strings as `const char[]`): SDL_INIT_VIDEO,
//     SDL_WINDOW_RESIZABLE, SDLK_A, SDL_HINT_*, SDL_PROP_* ...;
//   - {len(funcs)} function-like macros as functions (tools/policy.py,
//     FUNCTION_MACROS): SDL_BUTTON_MASK, SDL_FOURCC, SDL_VERSIONNUM, SDL_min,
//     SDL_zero, SDL_CreateThread ... Each body is the macro itself, expanded
//     here while it is defined; every argument is evaluated once.
//
// Each is defined where its header defines it (#ifdef). {side} macros stay
// macros — stringification, token pasting, attributes, assertions, the
// platform tests, SDL 2's names — in <mwrap/sdl3/macros.hpp>, and {excluded} are
// not API; tools/check_exports.py accounts for every one.
module;
''' + INCLUDES + '''
export module mcpplibs.mwrap.sdl3.macros;

// The macros' values and expansions, captured while they are defined.
namespace mwrap_sdl3_macros {
''']
    for n, h, k in consts:
        out.append(f'#ifdef {n}')
        if k == 'string':
            out.append(f'inline constexpr char v_{n}[] = {n};')
        else:
            out.append(f'inline constexpr auto v_{n} = {n};')
        out.append('#endif')
    for n, h in funcs:
        tmpl, ret, params, kind = policy.FUNCTION_MACROS[n]
        if kind == 'outofline':
            continue
        args = ', '.join(arg_names(params))
        head = (tmpl + ' ' if tmpl else '') + ('constexpr ' if kind == 'constexpr' else 'inline ')
        body = f'{n}({args});' if kind == 'statement' else f'return {n}({args});'
        out.append(f'#ifdef {n}')
        out.append(f'{head}{ret} f_{n}({params}) {{ {body} }}')
        out.append('#endif')
    out.append('}  // namespace mwrap_sdl3_macros\n')
    out.append('export namespace mcpplibs::mwrap::sdl3::macros {')
    header = None
    for n, h, k in consts:
        if h != header:
            out.append(f'\n// <SDL3/{h}>')
            header = h
        out.append(f'#ifdef {n}')
        out.append(f'#undef {n}')
        if k == 'string':
            out.append(f'inline constexpr auto &{n} = mwrap_sdl3_macros::v_{n};')
        else:
            out.append(f'inline constexpr auto {n} = mwrap_sdl3_macros::v_{n};')
        out.append('#endif')
    out.append('\n// Function-like macros.')
    for n, h in funcs:
        tmpl, ret, params, kind = policy.FUNCTION_MACROS[n]
        args = ', '.join(arg_names(params))
        out.append(f'#ifdef {n}')
        out.append(f'#undef {n}')
        if kind == 'outofline':
            out.append(f'{ret} {n}({params});')
        else:
            head = (tmpl + ' ' if tmpl else '') + ('constexpr ' if kind == 'constexpr' else 'inline ')
            call = f'mwrap_sdl3_macros::f_{n}({args})'
            body = f'{call};' if kind == 'statement' else f'return {call};'
            out.append(f'{head}{ret} {n}({params}) {{ {body} }}')
        out.append('#endif')
    out.append('\n}  // namespace mcpplibs::mwrap::sdl3::macros\n')
    cppm = '\n'.join(out)

    outofline = [(n, h) for n, h in funcs if policy.FUNCTION_MACROS[n][3] == 'outofline']
    impl = [NOTICE, '''//
// The function macros that may call a static inline function of the headers
// (SDL_SwapFloat; SDL_Swap16 &c. without a compiler builtin), defined here
// rather than inline in the interface, where that would expose it.
module;
''' + INCLUDES + '''
module mcpplibs.mwrap.sdl3.macros;

namespace {
''']
    for n, h in outofline:
        _, ret, params, _ = policy.FUNCTION_MACROS[n]
        args = ', '.join(arg_names(params))
        impl.append(f'#ifdef {n}')
        impl.append(f'{ret} call_{n}({params}) {{ return {n}({args}); }}')
        impl.append('#endif')
    impl.append('}  // namespace\n')
    impl.append('namespace mcpplibs::mwrap::sdl3::macros {\n')
    for n, h in outofline:
        _, ret, params, _ = policy.FUNCTION_MACROS[n]
        args = ', '.join(arg_names(params))
        impl.append(f'#ifdef {n}')
        impl.append(f'#undef {n}')
        impl.append(f'{ret} {n}({params}) {{ return call_{n}({args}); }}')
        impl.append('#endif')
    impl.append('\n}  // namespace mcpplibs::mwrap::sdl3::macros\n')
    return cppm, '\n'.join(impl)


def render_all(s: Surface):
    table = macro_table(s)
    errors = [f'{n} ({h}): {r}' for n, h, k, r in table if k == 'error']
    if errors:
        sys.exit('unclassified macros:\n  ' + '\n  '.join(errors))
    cppm, impl = render_module(s, set(s.macros))
    mcppm, mimpl = render_macros(s, table)
    return {'src/sdl3.cppm': cppm, 'src/inline.cpp': impl, 'src/macros.cppm': mcppm, 'src/macros.cpp': mimpl}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    s = surface(fetch(root))
    stale = []
    for rel, text in render_all(s).items():
        path = root / rel
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', rel)
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
